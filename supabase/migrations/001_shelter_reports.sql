create table if not exists public.crowd_reports (
  id bigint generated by default as identity primary key,
  shelter_name text not null,
  shelter_type text not null check (shelter_type in ('summer','winter')),
  status text not null check (status in ('여유','보통','혼잡')),
  created_at timestamptz not null default now()
);

alter table public.crowd_reports enable row level security;

create policy "public can insert crowd reports"
on public.crowd_reports
for insert
to anon, authenticated
with check (true);

create policy "public can read recent crowd reports"
on public.crowd_reports
for select
to anon, authenticated
using (created_at > now() - interval '3 hours');
